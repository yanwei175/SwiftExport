using System.ComponentModel.DataAnnotations.Schema;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using SwiftExport.Core.Common;
using SwiftExport.Core.DatabaseSchema;
using SwiftExport.Infrastructure.Repositories.Base;

namespace SwiftExport.Infrastructure.DatabaseSchema;

/// <summary>从实体元数据生成PostgreSQL 18空库结构评审基线；不连接数据库、不迁数据、不替换SQL Server生成器。</summary>
public sealed class PostgreSqlSchemaGenerator
{
    /// <summary>生成表、序列、索引、CHECK、保护触发器及中文说明；未知类型或命名碰撞立即失败。</summary>
    public string Generate(Assembly entityAssembly)
    {
        ArgumentNullException.ThrowIfNull(entityAssembly);
        var entities = entityAssembly.GetTypes().Where(t => !t.IsAbstract && t.GetCustomAttribute<TableAttribute>() is not null)
            .OrderBy(t => Map(t).TableName, StringComparer.Ordinal).ToArray();
        if (entities.Any(t => !typeof(BaseEntity).IsAssignableFrom(t))) throw new InvalidOperationException("持久化实体必须继承BaseEntity。");
        var names = new HashSet<string>(StringComparer.Ordinal);
        string Register(string name)
        {
            var physical = PostgreSqlNames.FromClr(name);
            if (!names.Add(physical)) throw new InvalidOperationException($"PostgreSQL对象名冲突：{physical}");
            return physical;
        }
        foreach (var entity in entities) Register(Map(entity).TableName);
        var sql = new StringBuilder("-- <auto-generated>\n-- PostgreSQL 18结构评审基线：比较规则及仓储事务适配尚未验收，不能作为正式切库依据。\n-- 仅空库结构；不含建库、历史数据迁移或数据库外键。\n-- </auto-generated>\nBEGIN;\n");
        sql.AppendLine("DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname NOT IN ('pg_catalog','information_schema') AND n.nspname NOT LIKE 'pg_toast%' AND c.relkind IN ('r','p','v','m','S','f')) THEN RAISE EXCEPTION '目标数据库不是空库，拒绝生成基线'; END IF; END $$;");
        var sequences = entities.SelectMany(t => Map(t).Columns).Select(c => c.Property.GetCustomAttribute<DbSequenceAttribute>()).OfType<DbSequenceAttribute>().GroupBy(s => s.Name).OrderBy(g => g.Key, StringComparer.Ordinal);
        if (entities.Any(t => IsDictionary(t) || t == typeof(SwiftExport.Core.Entities.MasterData.Customer)
                || t == typeof(SwiftExport.Core.Entities.MasterData.Supplier)))
        {
            // 已批准字典及客户/供应商编码使用此规则；不将全部主数据列隐式改为 ICU。
            sql.AppendLine("CREATE COLLATION public.erp_dictionary_ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false);");
            // 将源库只读核验的常见比较样例放入目标初始化事务，ICU版本不满足时拒绝继续建表。
            sql.AppendLine("""
DO $$ BEGIN
IF NOT ('Unit' COLLATE public.erp_dictionary_ci = 'unit'
    AND rtrim('Unit ', ' ') COLLATE public.erp_dictionary_ci = 'Unit'
    AND 'A' COLLATE public.erp_dictionary_ci = 'Ａ'
    AND 'あ' COLLATE public.erp_dictionary_ci = 'ア'
    AND 'e' COLLATE public.erp_dictionary_ci <> 'é'
    AND ' Unit' COLLATE public.erp_dictionary_ci <> 'Unit'
    AND 'UNIT' COLLATE public.erp_dictionary_ci LIKE '%unit%' ESCAPE '')
THEN RAISE EXCEPTION '字典比较规则未通过源库对照样例，拒绝初始化'; END IF;
END $$;
""");
        }
        foreach (var group in sequences)
        {
            var sequence = group.First();
            if (group.Any(s => s.StartValue != sequence.StartValue || s.IncrementBy != sequence.IncrementBy)) throw new InvalidOperationException("同名序列配置冲突。");
            sql.AppendLine($"CREATE SEQUENCE public.{Q(Register(sequence.Name))} AS bigint START WITH {sequence.StartValue} INCREMENT BY {sequence.IncrementBy};");
        }
        foreach (var entity in entities)
        {
            var map = Map(entity);
            var columns = map.Columns.Select(c =>
            {
                if (c.Property.GetCustomAttribute<ForeignKeyAttribute>() is not null) throw new InvalidOperationException("不允许数据库外键属性。");
                var collation = IsDictionary(entity) && c.Property.PropertyType == typeof(string)
                    ? " COLLATE public.erp_dictionary_ci" : "";
                var definition = $"    {Q(c.ColumnName)} {ResolveType(c.Property)}{collation}{(EntityColumnSchema.IsNullable(c.Property) ? " NULL" : " NOT NULL")}";
                var value = c.Property.GetCustomAttribute<DbColumnAttribute>()?.DefaultExpression;
                if (value is not null) definition += " DEFAULT " + Default(c.Property, value);
                return definition;
            }).ToList();
            columns.Add($"    CONSTRAINT {Q(Register("pk_" + map.TableName))} PRIMARY KEY ({Q(map.KeyName)})");
            foreach (var check in entity.GetCustomAttributes<DbCheckAttribute>(true).OrderBy(c => c.Name, StringComparer.Ordinal))
                columns.Add($"    CONSTRAINT {Q(Register(check.Name.Replace("{Table}", entity.Name, StringComparison.Ordinal)))} CHECK ({PostgreSqlSchemaExpressions.Convert(entity, check.Expression)})");
            sql.AppendLine($"CREATE TABLE {Table(entity)} (\n{string.Join(",\n", columns)}\n);");
        }
        foreach (var entity in entities)
        {
            foreach (var index in entity.GetCustomAttributes<DbIndexAttribute>(true).OrderBy(i => i.Name, StringComparer.Ordinal))
            {
                if (index.Columns.Count == 0) throw new InvalidOperationException("索引没有键列。");
                var include = index.IncludeColumns.Length == 0 ? "" : $" INCLUDE ({string.Join(", ", index.IncludeColumns.Select(c => Column(entity, c)))})";
                var filter = string.IsNullOrWhiteSpace(index.Filter) ? "" : " WHERE " + PostgreSqlSchemaExpressions.Convert(entity, index.Filter);
                var keys = index.Columns.Select(c => IndexColumn(entity, index, c));
                sql.AppendLine($"CREATE {(index.IsUnique ? "UNIQUE " : "")}INDEX {Q(Register(index.Name))} ON {Table(entity)} ({string.Join(", ", keys)}){include}{filter};");
            }
            WriteProtection(sql, entity, Register);
        }
        WriteDescriptions(sql, entityAssembly, entities);
        sql.AppendLine("COMMIT;");
        return sql.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    /// <summary>列级比较规则仅用于两个字典实体；客户、供应商只调整指定编码索引。</summary>
    private static bool IsDictionary(Type entity) => entity == typeof(SwiftExport.Core.Entities.Systems.Dictionaries.Types.SysDictType)
        || entity == typeof(SwiftExport.Core.Entities.Systems.Dictionaries.Data.SysDictData);

    /// <summary>仅对已批准的编码索引增加尾空格与 ICU 规则；保留其他索引、列定义及原存储文本。</summary>
    private static string IndexColumn(Type entity, DbIndexAttribute index, string property)
    {
        if (IsDictionary(entity) && property == "DictCode") return $"rtrim({Column(entity, property)}, ' ')";
        var partyCode = entity == typeof(SwiftExport.Core.Entities.MasterData.Customer)
                && index.Name == "UX_Customer_CustomerCode" && property == "CustomerCode"
            || entity == typeof(SwiftExport.Core.Entities.MasterData.Supplier)
                && index.Name == "UX_Supplier_SupplierCode" && property == "SupplierCode";
        return partyCode ? $"(rtrim({Column(entity, property)}, ' ') COLLATE public.erp_dictionary_ci)" : Column(entity, property);
    }

    /// <summary>显式适配当前类型注解，未知存储类型不回退成text；UTC与业务本地时间分开。</summary>
    internal static string ResolveType(PropertyInfo property)
    {
        var type = EntityColumnSchema.ResolveStoreType(property).ToLowerInvariant();
        if (type == "uniqueidentifier") return "uuid";
        if (type == "bit") return "boolean";
        if (type == "int") return "integer";
        if (type is "bigint" or "smallint" or "date") return type;
        if (type == "tinyint") throw new InvalidOperationException("tinyint需显式范围约束后适配。");
        if (type == "float") return "double precision";
        if (Regex.IsMatch(type, @"^decimal\(\d+,\d+\)$")) return type.Replace("decimal", "numeric", StringComparison.Ordinal);
        if (type is "nvarchar(max)" or "varchar(max)") return "text";
        if (Regex.IsMatch(type, @"^n?varchar\(\d+\)$")) return type.TrimStart('n');
        if (type == "varbinary(max)") return "bytea";
        if (type == "datetime2(7)") return property.Name.EndsWith("Utc", StringComparison.Ordinal) ? "timestamp(6) with time zone" : "timestamp(6) without time zone";
        if (type == "datetimeoffset(7)") return "timestamp(6) with time zone";
        throw new InvalidOperationException($"{property.DeclaringType?.Name}.{property.Name}的类型{type}尚未适配。");
    }

    /// <summary>默认值只接受当前元数据使用的常量；不隐式转换时间、序列或提供者函数。</summary>
    private static string Default(PropertyInfo property, string expression)
    {
        if ((Nullable.GetUnderlyingType(property.PropertyType) ?? property.PropertyType) == typeof(bool))
            return expression switch { "0" => "FALSE", "1" => "TRUE", _ => throw new InvalidOperationException("未适配布尔默认值。") };
        if (Regex.IsMatch(expression, @"^-?\d+(\.\d+)?$")) return expression;
        throw new InvalidOperationException($"未适配默认表达式：{expression}");
    }

    /// <summary>生成只追加、身份不可变及已存在事实引用的冻结防线；并发引用协议仍须仓储实库验收。</summary>
    private static void WriteProtection(StringBuilder sql, Type entity, Func<string, string> register)
    {
        var immutable = entity.GetCustomAttribute<DbImmutableColumnsAttribute>();
        var appendOnly = entity.GetCustomAttribute<DbAppendOnlyAttribute>() is not null;
        if (appendOnly && immutable is not null) throw new InvalidOperationException("实体保护规则互斥。");
        if (appendOnly) Trigger("append_only", "UPDATE OR DELETE", "RAISE EXCEPTION USING ERRCODE = 'P3100', MESSAGE = '只追加事实禁止更新或删除';");
        if (immutable is not null)
            Trigger("immutable_identity", "UPDATE", $"IF {string.Join(" OR ", immutable.Columns.Select(c => $"NEW.{Column(entity, c)} IS DISTINCT FROM OLD.{Column(entity, c)}"))} THEN RAISE EXCEPTION USING ERRCODE = 'P3101', MESSAGE = '成立身份不可修改'; END IF;");
        foreach (var group in entity.GetCustomAttributes<DbFreezeColumnOnReferenceAttribute>().GroupBy(r => r.Column).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            sql.AppendLine("-- 评审限制：引用冻结只检查当前可见事实；并发新增引用的锁协议尚待仓储适配，不能用于正式部署。");
            var references = group.OrderBy(r => r.ReferencingEntity.FullName, StringComparer.Ordinal).Select(r => $"EXISTS (SELECT 1 FROM {Table(r.ReferencingEntity)} r WHERE r.{Column(r.ReferencingEntity, r.ReferencingColumn)} = OLD.{Column(entity, nameof(BaseEntity.Uid))})");
            Trigger(group.Key + "_frozen_on_reference", "UPDATE", $"IF NEW.{Column(entity, group.Key)} IS DISTINCT FROM OLD.{Column(entity, group.Key)} AND ({string.Join(" OR ", references)}) THEN RAISE EXCEPTION USING ERRCODE = 'P3102', MESSAGE = '已被事实引用的字段禁止修改'; END IF;");
        }
        void Trigger(string suffix, string events, string body)
        {
            var function = register("fn_" + Map(entity).TableName + "_" + suffix);
            var trigger = register("tr_" + Map(entity).TableName + "_" + suffix);
            sql.AppendLine($"CREATE FUNCTION public.{Q(function)}() RETURNS trigger LANGUAGE plpgsql AS $body$ BEGIN {body} RETURN NEW; END; $body$;");
            sql.AppendLine($"CREATE TRIGGER {Q(trigger)} BEFORE {events} ON {Table(entity)} FOR EACH ROW EXECUTE FUNCTION public.{Q(function)}();");
        }
    }

    /// <summary>沿用Core中文XML说明，写入COMMENT，不复制SQL Server扩展属性语法。</summary>
    private static void WriteDescriptions(StringBuilder sql, Assembly assembly, IEnumerable<Type> entities)
    {
        var path = Path.ChangeExtension(assembly.Location, ".xml");
        if (!File.Exists(path)) throw new InvalidOperationException("缺少Core XML文档，请先构建。");
        var docs = XDocument.Load(path).Descendants("member").Where(m => m.Attribute("name") is not null)
            .ToDictionary(m => (string)m.Attribute("name")!, m => Regex.Replace(m.Element("summary")?.Value.Trim() ?? "", @"\s+", " "));
        string Description(string key, string fallback) => "'" + (docs.TryGetValue(key, out var value) && value.Length > 0 ? value : fallback).Replace("'", "''", StringComparison.Ordinal) + "'";
        foreach (var entity in entities)
        {
            sql.AppendLine($"COMMENT ON TABLE {Table(entity)} IS {Description("T:" + entity.FullName, entity.Name + "持久化表。")};");
            foreach (var column in Map(entity).Columns)
                sql.AppendLine($"COMMENT ON COLUMN {Table(entity)}.{Q(column.ColumnName)} IS {Description("P:" + column.Property.DeclaringType!.FullName + "." + column.PropertyName, column.PropertyName + "数据字段。")};");
        }
    }

    private static EntityMetadata Map(Type entity) => PostgreSqlEntityMetadata.GetMetadata(entity);
    private static string Q(string name) => PostgreSqlNames.Quote(name);
    private static string Table(Type entity) => $"{Q(Map(entity).SchemaName)}.{Q(Map(entity).TableName)}";
    private static string Column(Type entity, string property) => Q(Map(entity).GetProperty(property).ColumnName);
}
