using System.ComponentModel.DataAnnotations.Schema;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using SwiftExport.Core.Common;
using SwiftExport.Core.DatabaseSchema;
using SwiftExport.Infrastructure.Repositories.Base;

namespace SwiftExport.Infrastructure.DatabaseSchema;

/// <summary>
/// 从 Core 持久化实体及其数据库元数据确定性生成全新 SQL Server 数据库结构。
/// 本生成器只建立空库结构，禁止承担旧库迁移、数据回填或数据库外键职责。
/// </summary>
public sealed class SqlServerSchemaGenerator
{
    private static readonly Regex ForbiddenRelationshipSql = new(
        @"\bFOREIGN\s+KEY\b|\bREFERENCES\b",
        RegexOptions.IgnoreCase | RegexOptions.CultureInvariant | RegexOptions.Compiled);

    /// <summary>验证并生成给定实体程序集的完整空库结构脚本。</summary>
    public string Generate(Assembly entityAssembly)
    {
        ArgumentNullException.ThrowIfNull(entityAssembly);
        var entities = DiscoverEntities(entityAssembly);
        Validate(entities);
        var documentation = LoadDocumentation(entityAssembly);

        var sql = new StringBuilder();
        sql.AppendLine("-- <auto-generated>");
        sql.AppendLine("-- 由 _tools/SchemaGenerator 根据 SwiftExport.Core 实体生成，禁止手工修改。");
        sql.AppendLine("-- 仅用于已创建的空 SQL Server 数据库；不包含历史迁移、数据回填或数据库外键。");
        sql.AppendLine("-- </auto-generated>");
        sql.AppendLine("SET NOCOUNT ON;");
        sql.AppendLine("SET XACT_ABORT ON;");
        sql.AppendLine("IF EXISTS (SELECT 1 FROM sys.tables WHERE is_ms_shipped = 0)");
        sql.AppendLine("    THROW 53000, N'目标数据库不是空库，实体基线拒绝执行。', 1;");
        sql.AppendLine("BEGIN TRANSACTION;");
        sql.AppendLine();

        WriteSequences(sql, entities);
        foreach (var entity in entities)
        {
            WriteTable(sql, entity);
        }
        foreach (var entity in entities)
        {
            WriteIndexes(sql, entity);
        }
        foreach (var entity in entities)
        {
            WriteProtectionTriggers(sql, entity);
            WriteReferenceFreezeTriggers(sql, entity);
        }
        WriteDescriptions(sql, entities, documentation);

        sql.AppendLine("COMMIT TRANSACTION;");
        var result = sql.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
        if (ForbiddenRelationshipSql.IsMatch(result))
            throw new InvalidOperationException("生成结果包含被禁止的数据库关系约束语句。");
        return result;
    }

    /// <summary>发现所有显式标注 TableAttribute 的非抽象实体。</summary>
    public IReadOnlyList<Type> DiscoverEntities(Assembly entityAssembly)
        => entityAssembly.GetTypes()
            .Where(type => !type.IsAbstract && type.GetCustomAttribute<TableAttribute>() is not null)
            .OrderBy(type => GetSchema(type), StringComparer.Ordinal)
            .ThenBy(type => GetTable(type), StringComparer.Ordinal)
            .ToArray();

    private void Validate(IReadOnlyList<Type> entities)
    {
        var entitySet = entities.ToHashSet();
        var tableNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var objectNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var entity in entities)
        {
            if (!typeof(BaseEntity).IsAssignableFrom(entity))
                throw new InvalidOperationException($"持久化类型 {entity.FullName} 必须继承 BaseEntity。");
            if (!tableNames.Add($"{GetSchema(entity)}.{GetTable(entity)}"))
                throw new InvalidOperationException($"实体 {entity.FullName} 使用了重复表名。");

            var properties = GetMappedProperties(entity);
            if (properties.All(property => property.Name != nameof(BaseEntity.Uid)))
                throw new InvalidOperationException($"实体 {entity.FullName} 缺少 Uid 主键。");
            if (properties.Any(property => property.GetCustomAttribute<ForeignKeyAttribute>() is not null))
                throw new InvalidOperationException($"实体 {entity.FullName} 使用了被禁止的 ForeignKeyAttribute。");

            foreach (var property in properties)
            {
                _ = ResolveStoreType(property);
            }

            foreach (var check in entity.GetCustomAttributes<DbCheckAttribute>(true))
            {
                var name = check.Name.Replace("{Table}", GetTable(entity), StringComparison.Ordinal);
                AddObjectName(objectNames, name, entity);
                if (string.IsNullOrWhiteSpace(check.Expression) || ForbiddenRelationshipSql.IsMatch(check.Expression))
                    throw new InvalidOperationException($"实体 {entity.Name} 的 CHECK {name} 无效。");
            }

            foreach (var index in entity.GetCustomAttributes<DbIndexAttribute>(true))
            {
                AddObjectName(objectNames, index.Name, entity);
                if (index.Columns.Count == 0)
                    throw new InvalidOperationException($"实体 {entity.Name} 的索引 {index.Name} 没有键列。");
                ValidateProperties(entity, properties, index.Columns.Concat(index.IncludeColumns), index.Name);
            }

            var appendOnly = entity.GetCustomAttribute<DbAppendOnlyAttribute>() is not null;
            var immutable = entity.GetCustomAttribute<DbImmutableColumnsAttribute>();
            if (appendOnly && immutable is not null)
                throw new InvalidOperationException($"实体 {entity.Name} 不能同时声明只追加和固定列触发器。");
            if (immutable is not null)
                ValidateProperties(entity, properties, immutable.Columns, nameof(DbImmutableColumnsAttribute));

            foreach (var freeze in entity.GetCustomAttributes<DbFreezeColumnOnReferenceAttribute>())
            {
                ValidateProperties(entity, properties, [freeze.Column], nameof(DbFreezeColumnOnReferenceAttribute));
                ValidateReference(freeze.ReferencingEntity, GetMappedProperties(freeze.ReferencingEntity),
                    freeze.ReferencingColumn, entity, nameof(BaseEntity.Uid), entitySet);
                if (!entitySet.Contains(freeze.ReferencingEntity))
                    throw new InvalidOperationException($"冻结规则的引用实体 {freeze.ReferencingEntity.Name} 不是持久化实体。");
            }

            foreach (var reference in entity.GetCustomAttributes<LogicalReferenceAttribute>())
            {
                ValidateReference(entity, properties, reference.LocalColumn, reference.PrincipalEntity,
                    reference.PrincipalColumn, entitySet);
            }
            foreach (var reference in entity.GetCustomAttributes<PolymorphicLogicalReferenceAttribute>())
            {
                ValidateProperties(entity, properties,
                    [reference.DiscriminatorColumn, reference.LocalColumn], nameof(PolymorphicLogicalReferenceAttribute));
                if (string.IsNullOrWhiteSpace(reference.DiscriminatorValue))
                    throw new InvalidOperationException($"实体 {entity.Name} 的多态逻辑关系缺少判别值。");
                ValidateReference(entity, properties, reference.LocalColumn, reference.PrincipalEntity,
                    reference.PrincipalColumn, entitySet);
            }
        }
    }

    private static void AddObjectName(ISet<string> names, string name, Type entity)
    {
        if (string.IsNullOrWhiteSpace(name) || name.Length > 128 || !names.Add(name))
            throw new InvalidOperationException($"实体 {entity.Name} 声明了无效或重复的数据库对象名 {name}。");
    }

    private static void ValidateReference(
        Type entity,
        IReadOnlyList<PropertyInfo> properties,
        string localColumn,
        Type principalEntity,
        string principalColumn,
        ISet<Type> entitySet)
    {
        ValidateProperties(entity, properties, [localColumn], nameof(LogicalReferenceAttribute));
        if (!entitySet.Contains(principalEntity))
            throw new InvalidOperationException($"实体 {entity.Name} 的逻辑关系目标 {principalEntity.Name} 不是持久化实体。");
        if (GetMappedProperties(principalEntity).All(property => property.Name != principalColumn))
            throw new InvalidOperationException($"逻辑关系目标 {principalEntity.Name}.{principalColumn} 不存在。");
    }

    private static void ValidateProperties(
        Type entity,
        IReadOnlyList<PropertyInfo> properties,
        IEnumerable<string> names,
        string owner)
    {
        var available = properties.Select(property => property.Name).ToHashSet(StringComparer.Ordinal);
        var missing = names.Where(name => !available.Contains(name)).Distinct(StringComparer.Ordinal).ToArray();
        if (missing.Length > 0)
            throw new InvalidOperationException($"实体 {entity.Name} 的 {owner} 引用了不存在的属性：{string.Join(", ", missing)}。");
    }

    private static void WriteSequences(StringBuilder sql, IReadOnlyList<Type> entities)
    {
        var sequences = entities
            .SelectMany(type => GetMappedProperties(type)
                .Select(property => property.GetCustomAttribute<DbSequenceAttribute>())
                .Where(attribute => attribute is not null)
                .Cast<DbSequenceAttribute>())
            .GroupBy(attribute => attribute.Name, StringComparer.OrdinalIgnoreCase)
            .Select(group => group.First())
            .OrderBy(attribute => attribute.Name, StringComparer.Ordinal)
            .ToArray();
        foreach (var sequence in sequences)
        {
            sql.Append("CREATE SEQUENCE [dbo].[").Append(Escape(sequence.Name)).Append("] AS bigint START WITH ")
                .Append(sequence.StartValue).Append(" INCREMENT BY ").Append(sequence.IncrementBy).AppendLine(";");
        }
        if (sequences.Length > 0) sql.AppendLine();
    }

    private void WriteTable(StringBuilder sql, Type entity)
    {
        var schema = GetSchema(entity);
        var table = GetTable(entity);
        var properties = GetMappedProperties(entity);
        foreach (var reference in entity.GetCustomAttributes<LogicalReferenceAttribute>())
        {
            sql.Append("-- 逻辑依赖: [").Append(GetColumn(properties.Single(p => p.Name == reference.LocalColumn)))
                .Append("] -> [").Append(GetSchema(reference.PrincipalEntity)).Append("].[" )
                .Append(GetTable(reference.PrincipalEntity)).Append("].[" )
                .Append(GetColumn(GetMappedProperties(reference.PrincipalEntity).Single(p => p.Name == reference.PrincipalColumn)))
                .AppendLine("]（由 Application 校验）");
        }
        foreach (var reference in entity.GetCustomAttributes<PolymorphicLogicalReferenceAttribute>())
        {
            sql.Append("-- 多态逻辑依赖: ").Append(reference.DiscriminatorColumn).Append("=")
                .Append(reference.DiscriminatorValue).Append(" 时 [").Append(reference.LocalColumn).Append("] -> [")
                .Append(GetSchema(reference.PrincipalEntity)).Append("].[" ).Append(GetTable(reference.PrincipalEntity))
                .AppendLine("]（由 Application 校验）");
        }

        sql.Append("CREATE TABLE [").Append(Escape(schema)).Append("].[").Append(Escape(table)).AppendLine("]");
        sql.AppendLine("(");
        var definitions = new List<string>();
        foreach (var property in properties)
        {
            var column = GetColumn(property);
            var definition = new StringBuilder("    [").Append(Escape(column)).Append("] ")
                .Append(ResolveStoreType(property)).Append(IsNullable(property) ? " NULL" : " NOT NULL");
            var database = property.GetCustomAttribute<DbColumnAttribute>(true);
            if (!string.IsNullOrWhiteSpace(database?.DefaultExpression))
            {
                definition.Append(" CONSTRAINT [DF_").Append(Escape(table)).Append('_').Append(Escape(column))
                    .Append("] DEFAULT (").Append(database.DefaultExpression).Append(')');
            }
            definitions.Add(definition.ToString());
        }
        definitions.Add($"    CONSTRAINT [PK_{Escape(table)}] PRIMARY KEY ([{Escape(GetColumn(properties.Single(p => p.Name == nameof(BaseEntity.Uid))))}])");
        definitions.AddRange(entity.GetCustomAttributes<DbCheckAttribute>(true)
            .OrderBy(attribute => attribute.Name, StringComparer.Ordinal)
            .Select(attribute => $"    CONSTRAINT [{Escape(attribute.Name.Replace("{Table}", table, StringComparison.Ordinal))}] CHECK ({attribute.Expression})"));
        sql.AppendLine(string.Join(",\n", definitions));
        sql.AppendLine(");");
        sql.AppendLine();
    }

    private static void WriteIndexes(StringBuilder sql, Type entity)
    {
        var properties = GetMappedProperties(entity);
        foreach (var index in entity.GetCustomAttributes<DbIndexAttribute>(true)
                     .OrderBy(attribute => attribute.Name, StringComparer.Ordinal))
        {
            sql.Append("CREATE ");
            if (index.IsUnique) sql.Append("UNIQUE ");
            sql.Append("INDEX [").Append(Escape(index.Name)).Append("] ON [")
                .Append(Escape(GetSchema(entity))).Append("].[").Append(Escape(GetTable(entity))).Append("] (")
                .Append(string.Join(", ", index.Columns.Select(name => $"[{Escape(GetColumn(properties.Single(p => p.Name == name)))}]")))
                .Append(')');
            if (index.IncludeColumns.Length > 0)
            {
                sql.Append(" INCLUDE (").Append(string.Join(", ", index.IncludeColumns.Select(name =>
                    $"[{Escape(GetColumn(properties.Single(p => p.Name == name)))}]"))).Append(')');
            }
            if (!string.IsNullOrWhiteSpace(index.Filter)) sql.Append(" WHERE ").Append(index.Filter);
            sql.AppendLine(";");
        }
        if (entity.GetCustomAttributes<DbIndexAttribute>(true).Any()) sql.AppendLine();
    }

    private static void WriteProtectionTriggers(StringBuilder sql, Type entity)
    {
        var schema = GetSchema(entity);
        var table = GetTable(entity);
        if (entity.GetCustomAttribute<DbAppendOnlyAttribute>() is not null)
        {
            var triggerName = $"TR_{table}_AppendOnly";
            var body = $"CREATE TRIGGER [{schema}].[{triggerName}] ON [{schema}].[{table}] INSTEAD OF UPDATE, DELETE AS BEGIN SET NOCOUNT ON; THROW 53100, N'{table} 是只追加事实，禁止更新或删除。', 1; END;";
            sql.Append("EXEC(N'").Append(body.Replace("'", "''", StringComparison.Ordinal)).AppendLine("');");
            sql.AppendLine();
            return;
        }

        var immutable = entity.GetCustomAttribute<DbImmutableColumnsAttribute>();
        if (immutable is null) return;
        var properties = GetMappedProperties(entity);
        var columns = immutable.Columns.Select(name => GetColumn(properties.Single(p => p.Name == name))).ToArray();
        var inserted = string.Join(", ", columns.Select(column => $"i.[{Escape(column)}]"));
        var deleted = string.Join(", ", columns.Select(column => $"d.[{Escape(column)}]"));
        var trigger = $"TR_{table}_ImmutableIdentity";
        var triggerSql = $"CREATE TRIGGER [{schema}].[{trigger}] ON [{schema}].[{table}] AFTER UPDATE AS BEGIN SET NOCOUNT ON; IF EXISTS (SELECT 1 FROM inserted i INNER JOIN deleted d ON d.[Uid]=i.[Uid] WHERE EXISTS (SELECT {inserted} EXCEPT SELECT {deleted})) THROW 53101, N'{table} 的成立身份不可修改。', 1; END;";
        sql.Append("EXEC(N'").Append(triggerSql.Replace("'", "''", StringComparison.Ordinal)).AppendLine("');");
        sql.AppendLine();
    }

    /// <summary>按实体声明生成引用后冻结触发器；逐行比较新旧值，未引用产品仍可纠正，已有历史不随余额归零解冻。</summary>
    private static void WriteReferenceFreezeTriggers(StringBuilder sql, Type entity)
    {
        var properties = GetMappedProperties(entity);
        var groups = entity.GetCustomAttributes<DbFreezeColumnOnReferenceAttribute>()
            .GroupBy(rule => rule.Column).OrderBy(group => group.Key, StringComparer.Ordinal);
        foreach (var group in groups)
        {
            var column = Escape(GetColumn(properties.Single(property => property.Name == group.Key)));
            var predicates = group.OrderBy(rule => rule.ReferencingEntity.FullName, StringComparer.Ordinal)
                .ThenBy(rule => rule.ReferencingColumn, StringComparer.Ordinal)
                .Select(rule =>
                {
                    var referenceColumn = GetColumn(GetMappedProperties(rule.ReferencingEntity)
                        .Single(property => property.Name == rule.ReferencingColumn));
                    // 范围锁使引用检查与单位更新处于同一数据库事务，避免检查后插入引用的窗口。
                    return $"EXISTS (SELECT 1 FROM [{Escape(GetSchema(rule.ReferencingEntity))}].[{Escape(GetTable(rule.ReferencingEntity))}] r WITH (UPDLOCK,HOLDLOCK) WHERE r.[{Escape(referenceColumn)}]=i.[Uid])";
                });
            var schema = Escape(GetSchema(entity));
            var table = Escape(GetTable(entity));
            var trigger = Escape($"TR_{GetTable(entity)}_{group.Key}_FrozenOnReference");
            var body = $"CREATE TRIGGER [{schema}].[{trigger}] ON [{schema}].[{table}] AFTER UPDATE AS BEGIN SET NOCOUNT ON; IF EXISTS (SELECT 1 FROM inserted i INNER JOIN deleted d ON d.[Uid]=i.[Uid] WHERE EXISTS (SELECT i.[{column}] EXCEPT SELECT d.[{column}]) AND ({string.Join(" OR ", predicates)})) THROW 53102, N'{table} 的 {column} 已被事实引用，禁止修改。', 1; END;";
            sql.Append("EXEC(N'").Append(body.Replace("'", "''", StringComparison.Ordinal)).AppendLine("');");
            sql.AppendLine();
        }
    }

    /// <summary>为所有持久化表和列写入 SQL Server MS_Description 扩展属性。</summary>
    private static void WriteDescriptions(
        StringBuilder sql,
        IReadOnlyList<Type> entities,
        IReadOnlyDictionary<string, string> documentation)
    {
        sql.AppendLine("-- 表和字段说明（来源于 SwiftExport.Core XML 文档）");
        foreach (var entity in entities)
        {
            var schema = GetSchema(entity);
            var table = GetTable(entity);
            WriteDescription(sql, schema, table, null,
                GetDescription(documentation, GetTypeMemberName(entity), $"{entity.Name} 持久化数据表。"));

            foreach (var property in GetMappedProperties(entity))
            {
                var declaringType = property.DeclaringType
                    ?? throw new InvalidOperationException($"属性 {property.Name} 缺少声明类型。");
                WriteDescription(sql, schema, table, GetColumn(property),
                    GetDescription(documentation, GetPropertyMemberName(declaringType, property.Name),
                        $"{property.Name} 数据字段。"));
            }
        }
        sql.AppendLine();
    }

    /// <summary>写入单个表或字段的 MS_Description，所有名称均作为 Unicode 字面量传递。</summary>
    private static void WriteDescription(
        StringBuilder sql,
        string schema,
        string table,
        string? column,
        string description)
    {
        sql.AppendLine("EXEC sys.sp_addextendedproperty");
        sql.Append("    @name=N'MS_Description', @value=N'").Append(EscapeSqlLiteral(description)).AppendLine("',");
        sql.Append("    @level0type=N'SCHEMA', @level0name=N'").Append(EscapeSqlLiteral(schema)).AppendLine("',");
        sql.Append("    @level1type=N'TABLE', @level1name=N'").Append(EscapeSqlLiteral(table)).Append('\'');
        if (column is null)
        {
            sql.AppendLine(";");
            return;
        }

        sql.AppendLine(",");
        sql.Append("    @level2type=N'COLUMN', @level2name=N'").Append(EscapeSqlLiteral(column)).AppendLine("';");
    }

    /// <summary>读取实体程序集旁的 XML 文档，使数据库说明与源码中文职责注释保持同源。</summary>
    private static IReadOnlyDictionary<string, string> LoadDocumentation(Assembly entityAssembly)
    {
        var documentationPath = Path.ChangeExtension(entityAssembly.Location, ".xml");
        if (!File.Exists(documentationPath))
            throw new InvalidOperationException($"缺少实体 XML 文档：{documentationPath}。请启用 GenerateDocumentationFile 后重新构建。");

        var document = XDocument.Load(documentationPath, LoadOptions.None);
        return document.Descendants("member")
            .Select(member => new
            {
                Name = (string?)member.Attribute("name"),
                Summary = NormalizeDescription(member.Element("summary")?.Value)
            })
            .Where(item => !string.IsNullOrWhiteSpace(item.Name) && !string.IsNullOrWhiteSpace(item.Summary))
            .ToDictionary(item => item.Name!, item => item.Summary!, StringComparer.Ordinal);
    }

    /// <summary>取得 XML 说明；未编写 summary 的成员使用稳定占位说明，保证每个表和字段均有描述。</summary>
    private static string GetDescription(
        IReadOnlyDictionary<string, string> documentation,
        string memberName,
        string fallback)
        => documentation.TryGetValue(memberName, out var description) ? description : fallback;

    private static string GetTypeMemberName(Type type) => $"T:{GetDocumentationTypeName(type)}";

    private static string GetPropertyMemberName(Type declaringType, string propertyName)
        => $"P:{GetDocumentationTypeName(declaringType)}.{propertyName}";

    private static string GetDocumentationTypeName(Type type)
        => (type.FullName ?? type.Name).Replace('+', '.');

    private static string? NormalizeDescription(string? value)
        => string.IsNullOrWhiteSpace(value)
            ? null
            : Regex.Replace(value.Trim(), @"\s+", " ", RegexOptions.CultureInvariant);

    private static string ResolveStoreType(PropertyInfo property) => EntityColumnSchema.ResolveStoreType(property);

    private static bool IsNullable(PropertyInfo property) => EntityColumnSchema.IsNullable(property);

    private static IReadOnlyList<PropertyInfo> GetMappedProperties(Type entity)
        => EntityMetadataCache.GetMetadata(entity).Columns.Select(column => column.Property).ToArray();

    private static string GetSchema(Type entity)
        => EntityMetadataCache.GetMetadata(entity).SchemaName;

    private static string GetTable(Type entity)
        => entity.GetCustomAttribute<TableAttribute>()?.Name
           ?? throw new InvalidOperationException($"类型 {entity.FullName} 缺少 TableAttribute。");

    private static string GetColumn(PropertyInfo property)
        => EntityMetadataCache.GetColumnName(property);

    private static string Escape(string identifier) => identifier.Replace("]", "]]", StringComparison.Ordinal);

    private static string EscapeSqlLiteral(string value) => value.Replace("'", "''", StringComparison.Ordinal);
}
